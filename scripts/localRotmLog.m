function w = localRotmLog(R)
% 将 SO(3) 旋转矩阵取主值对数，输出单位为弧度的三分量旋转向量。
    % 用 trace(R)=1+2cos(theta) 求旋转角的余弦。
    c = (trace(R)-1)/2;
    % 把余弦限制在 [-1,1] 内，防止浮点误差使 acos 产生复数。
    c = max(-1,min(1,c));
    % 反余弦求得主值旋转角，取值为 0 到 pi。
    th = acos(c);
    % 取 R 的反对称部分对应的三维轴向向量。
    v = [R(3,2)-R(2,3); R(1,3)-R(3,1); R(2,1)-R(1,2)];
    % 对于接近零角度的旋转，使用矩阵对数的一阶近似。
    if th < 1e-8
        % 此时旋转向量约等于反对称部分的一半。
        w = 0.5*v;
    % 角度没有逼近 pi 时进入常规公式分支。
    elseif (pi-th) > 1e-5
        % 用 theta/(2sin theta) 把反对称部分换算为旋转向量。
        w = (th/(2*sin(th)))*v;
    % 对于接近 pi 的旋转，使用避免除以极小 sin(theta) 的分支。
    else
        % 接近 pi 时 sin(theta) 很小，改用对称部分稳定求旋转轴。
        % 构造接近轴向外积的对称矩阵。
        A = (R+eye(3))/2;
        % 找出最适合恢复轴向的最大对角元位置。
        [~,k] = max(diag(A));
        % 初始化三分量旋转轴。
        axisVec = zeros(3,1);
        % 用所选对角元的平方根恢复对应轴分量。
        axisVec(k) = sqrt(max(A(k,k),0));
        % 若该分量仍非常小，则采用特征分解备用方案。
        if axisVec(k) < 1e-8
            % 对 R 的对称部分求特征值和特征向量。
            [V,D] = eig((R+R')/2);
            % 找到特征值最接近 1 的旋转轴方向。
            [~,ii] = min(abs(diag(D)-1));
            % 把相应实特征向量当作旋转轴。
            axisVec = real(V(:,ii));
        % 轴分量足够大时按矩阵非对角元恢复其他分量。
        else
            % 循环求出三个轴分量。
            for j = 1:3
                % 只计算主轴分量以外的位置。
                if j ~= k
                    % 由对称矩阵关系恢复第 j 个轴分量。
                    axisVec(j) = (R(j,k)+R(k,j))/(4*axisVec(k));
                % 结束是否为其他分量的判断。
                end
            % 结束逐分量循环。
            end
        % 结束旋转轴备用恢复方法分支。
        end
        % 计算恢复出的轴向量长度。
        axisNorm = norm(axisVec);
        % 若长度接近机器精度，则不能稳定归一化。
        if axisNorm < eps
            % 使用单位 x 方向作为退化情形的备用轴。
            axisVec = [1;0;0];
        % 轴长度足够时进入正常分支。
        else
            % 将旋转轴归一化为单位向量。
            axisVec = axisVec/axisNorm;
        % 结束轴向量长度判断。
        end
        % 反对称部分有足够信息时，用它确定旋转轴的正负方向。
        % 若反对称部分可辨别符号，且轴与其方向相反，就纠正方向。
        if norm(v) > 1e-8 && dot(axisVec,v) < 0
            % 翻转旋转轴的符号。
            axisVec = -axisVec;
        % 结束轴方向判断。
        end
        % 用主值角乘单位轴得到旋转向量。
        w = th*axisVec;
    % 结束接近零角、一般角及接近 pi 的三种情况。
    end
% 结束旋转矩阵对数局部函数。
end

